import { MorphIcon } from "morphicons/react";
import { Play, AudioLines } from "lucide";
import { Check, Undo2 } from "lucide-react";
import { cn } from "../lib/cn";
import type { Voice } from "../lib/types";
import { Card } from "./Card";
import { Chip } from "./Chip";
import { VoiceAvatar } from "./VoiceAvatar";
import { Waveform } from "./Waveform";
import { Button } from "./Button";
import { VoiceSourceBadge } from "./VoiceSourceBadge";
import type { VoiceSource } from "@readaloud/tokens";

export interface VoiceCardProps {
  voice: Voice;
  selected?: boolean;
  previewing?: boolean;
  /** The preview is still being generated by the speech server: nothing can be heard yet. */
  generating?: boolean;
  source?: VoiceSource;
  onPreview: () => void;
  onSelect: () => void;
  /** Offers to take the voice out of this list (e.g. send a gallery voice back to Studio). */
  onRemove?: () => void;
  /** Accessible name for the remove control; defaults to "Remove <name>". */
  removeLabel?: string;
  /** Short status under the language, e.g. how much of a document this voice has prepared. */
  note?: string;
  className?: string;
}

export function VoiceCard({ voice, selected, previewing, generating, source, onPreview, onSelect, onRemove, removeLabel, note, className }: VoiceCardProps) {
  const waiting = !!previewing && !!generating;
  return (
    <Card interactive selected={selected} className={cn("flex min-h-[200px] flex-col gap-3.5", className)} data-voice={voice.id}>
      <div className="flex items-center justify-between">
        <VoiceAvatar voice={voice} size={40} />
        <div className="flex items-center gap-2">
          {selected ? (
            <span className="inline-flex items-center gap-1 text-[12px] font-semibold text-accent">
              <Check size={16} strokeWidth={1.5} aria-hidden />
              Selected
            </span>
          ) : null}
          {onRemove ? (
            <button
              type="button"
              onClick={onRemove}
              aria-label={removeLabel ?? `Remove ${voice.name}`}
              title={removeLabel ?? `Remove ${voice.name}`}
              className="grid size-8 place-items-center rounded-control border-0 bg-transparent text-fg2 hover:bg-bg3 hover:text-fg"
            >
              <Undo2 size={16} strokeWidth={1.5} aria-hidden />
            </button>
          ) : null}
        </div>
      </div>
      <div className="flex flex-col gap-0.5">
        <div className="text-[16px] font-semibold">{voice.name}</div>
        <div className="font-mono text-[12px] text-fg2">{voice.lang}</div>
        {note && <div className="text-[12px] text-fg2">{note}</div>}
      </div>
      <div className="flex flex-wrap gap-1.5">
        {source && <span aria-label={`Voice source: ${source}`}><VoiceSourceBadge source={source} /></span>}
        {voice.tags.map((t) => (
          <Chip key={t} tag>
            {t}
          </Chip>
        ))}
      </div>
      <div className="mt-auto flex gap-2">
        <button
          type="button"
          onClick={onPreview}
          aria-label={waiting ? `Generating preview of ${voice.name}` : previewing ? `Playing preview of ${voice.name}` : `Preview ${voice.name}`}
          aria-pressed={!!previewing}
          aria-busy={waiting || undefined}
          className="inline-flex h-9 flex-1 items-center gap-2 rounded-control border border-line bg-bg px-3 text-[13px] text-fg hover:bg-bg3"
        >
          <MorphIcon icon={previewing ? AudioLines : Play} size={16} strokeWidth={1.5} reducedMotion="user" style={{ display: "block" }} />
          <Waveform active={!!previewing && !waiting} />
          {waiting ? "Generating…" : previewing ? "Playing…" : "Preview"}
        </button>
        <Button
          variant={selected ? "secondary" : "primary"}
          size="sm"
          onClick={onSelect}
          aria-pressed={selected}
          className={cn("h-9 px-3.5 font-semibold", selected && "cursor-default border-0 bg-bg3 text-fg")}
        >
          {selected ? "Selected" : "Use"}
        </Button>
      </div>
    </Card>
  );
}
